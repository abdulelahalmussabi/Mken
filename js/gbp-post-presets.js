window.MkenGbpPostPresets.getForActivity = function (activityId) {
  var map = window.MkenGbpPostPresets;
  if (activityId && map[activityId] && map[activityId].length) {
    return map[activityId].concat(map.default || []);
  }
  return map.default || [];
};
